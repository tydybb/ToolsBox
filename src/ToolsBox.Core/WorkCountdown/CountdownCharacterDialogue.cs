    public const int InteractionCount = 4;

    public static string Stage(string? name, string? effectKey, int sequence = 0)
    {
        string[] lines = Characters[CharacterIndex(name)].Stages[EffectIndex(effectKey)];
        return lines[Cycle(sequence, lines.Length)];
    }

    public static string Hover(string? name, string? effectKey) =>
        Characters[CharacterIndex(name)].Hovers[EffectIndex(effectKey)];

    public static string Click(string? name, int sequence) =>
        Characters[CharacterIndex(name)].Clicks[Cycle(sequence, InteractionCount)];

    private static int Cycle(int sequence, int count) => (sequence % count + count) % count;

